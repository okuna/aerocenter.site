#!/usr/bin/env node
/**
 * Generate radar/eram/index.html from the vendored scope page.
 *
 * The vendored scope (radar/eram/vendor/) is upstream code kept byte-for-byte
 * as fetched, so it can be refreshed by re-downloading without losing local
 * edits. All aerocenter-specific wiring lives outside it: this script rewrites
 * the server-absolute asset paths to relative ones and injects the simulation
 * bridge ahead of eram.js, which calls connectWs() at parse time.
 *
 * Usage:  node scripts/build-eram-page.js
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const VENDOR = path.join(ROOT, 'radar/eram/vendor');
const OUT = path.join(ROOT, 'radar/eram/index.html');

// Server-absolute path -> path relative to radar/eram/.
const REWRITES = [
	[/href="\/shared\/([\w.-]+)(\?[^"]*)?"/g, 'href="vendor/shared/$1"'],
	[/src="\/shared\/([\w.-]+)(\?[^"]*)?"/g, 'src="vendor/shared/$1"'],
	[/href="\/eram\/([\w.-]+)(\?[^"]*)?"/g, 'href="vendor/eram/$1"'],
	[/src="\/eram\/([\w.-]+)(\?[^"]*)?"/g, 'src="vendor/eram/$1"'],
	[/src="\/([\w.-]+\.js)(\?[^"]*)?"/g, 'src="vendor/$1"'],
];

const BANNER = `<!--
	GENERATED by scripts/build-eram-page.js — do not edit directly.

	The ERAM scope under vendor/ is third-party code from
	https://github.com/yanjz124/SwimReader (tools/SwimServer/wwwroot), used with
	the author's permission and kept unmodified. See vendor/NOTICE.

	Local wiring is scenario-player.js + sim-bridge.js, which feed the scope from
	a saved scenario instead of a live FAA SWIM feed.
-->
`;

function main() {
	const src = path.join(VENDOR, 'eram/scope.html');
	if (!fs.existsSync(src)) throw new Error(`missing vendored scope: ${src}`);
	let html = fs.readFileSync(src, 'utf8');

	for (const [re, to] of REWRITES) html = html.replace(re, to);

	// Leaflet is vendored (BSD-2-Clause) rather than pulled from unpkg, so the
	// scope keeps working without third-party CDN availability.
	html = html.replace(
		/https:\/\/unpkg\.com\/leaflet@[\d.]+\/dist\/leaflet\.(js|css)/g,
		'vendor/leaflet/leaflet.$1',
	);

	// The replay bar talks to a ReplayServer we do not have; the simulation owns
	// its own timeline, so drop it rather than ship a visibly broken control.
	html = html.replace(/[ \t]*<script[^>]*replay-bar\.js[^>]*><\/script>\n?/g, '');
	html = html.replace(/[ \t]*<link[^>]*replay-bar\.css[^>]*>\n?/g, '');

	// eram.css declares @font-face against a server-absolute /ERAMv110.ttf, which
	// 404s on a static host. Emit a patched copy beside the page (vendor/ stays
	// byte-identical to upstream) and point the stylesheet link at it.
	const cssOut = path.join(ROOT, 'radar/eram/eram.css');
	const css = fs.readFileSync(path.join(VENDOR, 'eram/eram.css'), 'utf8')
		.replace(/url\(['"]?\/ERAMv110\.ttf['"]?\)/g, "url('vendor/ERAMv110.ttf')");
	fs.writeFileSync(cssOut,
		'/* GENERATED by scripts/build-eram-page.js from vendor/eram/eram.css.\n'
		+ '   Only the @font-face URL is changed; see vendor/NOTICE. */\n' + css);
	html = html.replace('href="vendor/eram/eram.css"', 'href="eram.css"');

	// Inject the bridge ahead of eram.js.
	const eramScript = /<script src="vendor\/eram\/eram\.js"><\/script>/;
	if (!eramScript.test(html)) throw new Error('could not find the eram.js script tag to inject before');
	html = html.replace(
		eramScript,
		'<script src="../sim/scenario-format.js"></script>\n'
		+ '<script src="../sim/scenario-player.js"></script>\n'
		+ '<script src="sim-bridge.js"></script>\n'
		+ '<script src="vendor/eram/eram.js"></script>\n'
		+ '<script defer src="scenario-loader.js"></script>',
	);

	// Point the home link back at the site root.
	html = html.replace(/href="\/"/g, 'href="../../"');

	// Cache-bust every local asset with a hash of its contents.
	//
	// The site deploys over FTP, overwriting files at the same URLs, so without
	// this a browser will happily keep a stale copy. That is not hypothetical:
	// it shipped a fresh scenario-loader.js against a cached scenario-player.js,
	// which reported "0/25 up" because the old player had no activateDue().
	// Hashing means the URL changes if and only if the file does.
	const PAGE_DIR = path.dirname(OUT);
	let busted = 0;
	html = html.replace(/(src|href)="([^"?:]+\.(?:js|css|ttf))"/g, (match, attr, rel) => {
		const file = path.resolve(PAGE_DIR, rel);
		if (!fs.existsSync(file)) return match;
		const hash = crypto.createHash('sha1').update(fs.readFileSync(file)).digest('hex').slice(0, 8);
		busted++;
		return `${attr}="${rel}?v=${hash}"`;
	});

	fs.writeFileSync(OUT, BANNER + html);

	const leftover = [...html.matchAll(/(?:src|href)="(\/[^"]*)"/g)].map(m => m[1]);
	console.log(`wrote ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes), ${busted} assets cache-busted`);
	if (leftover.length) {
		console.log(`note: ${leftover.length} absolute path(s) left for the bridge to serve: ${[...new Set(leftover)].join(', ')}`);
	}
}

main();
